require("dotenv").config();
const express = require("express");
const cors = require("cors");
const dotenv = require("dotenv");
const path = require("path");

const connectDB = require("./config/db");

const authRoutes = require("./routes/authRoutes");
const conflictRoutes = require("./routes/conflictRoutes");
const wildlifeRoutes = require("./routes/wildlifeRoutes");
const restorationRoutes = require("./routes/restorationRoutes");
const uploadRoutes = require("./routes/uploadRoutes");
const elephantDetectionRoutes = require("./routes/elephantDetectionRoutes");
const blockchainRoutes = require("./routes/blockchainRoutes");

const { protect } = require("./middleware/authMiddleware");

dotenv.config();

connectDB();

const app = express();

app.use(cors());
app.use(express.json());
app.use(express.urlencoded({ extended: true }));


// ============================================================
// API ROUTES
// ============================================================

app.use("/api/auth", authRoutes);
app.use("/api/conflicts", conflictRoutes);
app.use("/api/wildlife", wildlifeRoutes);
app.use("/api/restoration", restorationRoutes);
app.use("/api/upload", uploadRoutes);
app.use("/api/elephant-detections", elephantDetectionRoutes);
app.use("/api/blockchain", blockchainRoutes);


// ============================================================
// NORMAL UPLOADS
// ============================================================

app.use(
    "/uploads",
    express.static(
        path.join(__dirname, "uploads")
    )
);


// ============================================================
// AI DETECTION IMAGES
// ============================================================
//
// YOLO detection images generated by the virtual camera
// are stored in:
//
// ForestSphere/
// └── m1-iot/
//     └── outputs/
//         └── detections/
//
// The frontend requests:
//
// /detection-images/<filename>
//
// This route exposes that folder to the dashboard.
//

const detectionImagesPath = path.join(
    __dirname,
    "..",
    "m1-iot",
    "outputs",
    "detections"
);

app.use(
    "/detection-images",
    express.static(detectionImagesPath)
);


// ============================================================
// ROOT ROUTE
// ============================================================

app.get("/", (req, res) => {

    res.json({
        message: "ForestSphere API is running"
    });

});


// ============================================================
// TEST PROTECTED ROUTE
// ============================================================

app.get(
    "/api/test-protected",
    protect,
    (req, res) => {

        res.json({
            message:
                "You accessed a protected ForestSphere route!",
            user: req.user
        });

    }
);


// ============================================================
// SERVER
// ============================================================

const PORT = process.env.PORT || 5000;

app.listen(PORT, () => {

    console.log(
        `ForestSphere server running on port ${PORT}`
    );

});